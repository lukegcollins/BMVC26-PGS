"""
Dual-Pair Sequence Dataset for Kinematic Orthogonality Training (KOT).

This dataset is the data-side counterpart to ``KOTLoss``.  It wraps two
``PairedSequenceDataset`` instances — one for spatial (FF++) real/fake
pairs and one for temporal (KiMoI pseudo-fake) real/fake pairs — and
stochastically samples from each based on the ``spatial_ratio`` parameter.

Data flow
---------
1. ``__getitem__`` is called with an index.
2. A coin flip (Bernoulli with p = ``spatial_ratio``) decides whether to
   yield a **spatial** pair (face-swap) or a **temporal** pair (kinematic).
3. The chosen inner dataset returns ``{real: [T,C,H,W], fake: [T,C,H,W],
   label: 1, meta: {...}}``.
4. The string ``"pair_type": "spatial"`` or ``"pair_type": "temporal"``
   is injected into the ``meta`` dictionary.
5. The Lightning training loop (``DeepfakeDetectorModule.training_step``)
   extracts ``pair_types`` from the batch metadata and passes them to
   ``KOTLoss.forward(outputs, labels, pair_types=pair_types)`` so the
   loss can route pairs to the correct OPA, GTL, and L_ortho branches.

Synchronized frequency wash
----------------------------
Temporal pseudo-fakes generated by KiMoI may carry frequency-domain
artefacts (Poisson blending seams, JPEG ghost patterns) that differ from
the real source.  To prevent the detector from exploiting these shortcuts,
a **synchronized frequency wash** applies identical random Gaussian noise
+ JPEG compression to *both* the real and fake clips in each pair:

- The same sigma and random seed are used for both clips, so any
  frequency-domain delta between them is eliminated.
- The wash is only applied to **temporal** pairs (spatial pairs from FF++
  already have matched compression characteristics).
- The wash is applied with probability ``freq_wash_prob`` (default 0.5),
  so the model still sees unwashed samples for robustness.

Returns the same dict format as PairedSequenceDataset::

    {real: [T,C,H,W], fake: [T,C,H,W], label: 1, meta: {..., pair_type: str}}
"""

from __future__ import annotations

import logging
import random

import numpy as np
import torch
from torch.utils.data import Dataset

logger = logging.getLogger(__name__)

# ImageNet normalization constants (used for denorm/renorm around freq wash)
_IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
_IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)


def _denormalize_imagenet(tensor: torch.Tensor) -> torch.Tensor:
    """Convert from ImageNet-normalized range back to [0, 1]."""
    return (tensor * _IMAGENET_STD + _IMAGENET_MEAN).clamp_(0.0, 1.0)


def _normalize_imagenet(tensor: torch.Tensor) -> torch.Tensor:
    """Convert from [0, 1] range to ImageNet-normalized."""
    return (tensor - _IMAGENET_MEAN) / _IMAGENET_STD


# ---------------------------------------------------------------------------
# Synchronized Frequency Wash
# ---------------------------------------------------------------------------
# The wash is applied dynamically in __getitem__ and never touches the saved
# dataset files on disk.  It consists of two stages:
#
# 1. Additive Gaussian noise (simulates sensor/ISO noise):
#    - sigma ~ Uniform[0, noise_sigma_max]  (default 0-5 on [0,255] scale)
#    - Same sigma and noise tensor shape used for both clips
#
# 2. JPEG compression wash:
#    - quality ~ Uniform[jpeg_quality_min, jpeg_quality_max]  (default 80-95)
#    - Same quality for both clips, applied frame-by-frame
#
# CRITICAL: The exact same random seed is used for both real and fake clips
# so that the frequency domain is perfectly unified between them.
# ---------------------------------------------------------------------------


def _apply_gaussian_noise(
    tensor: torch.Tensor,
    sigma: float,
    generator: torch.Generator,
) -> torch.Tensor:
    """Add Gaussian noise to a [T, C, H, W] float tensor in [0, 1].

    Uses the provided ``generator`` for reproducible noise that matches
    between the real and fake clips.
    """
    if sigma < 1e-6:
        return tensor
    noise = torch.empty_like(tensor).normal_(0, sigma, generator=generator)
    return (tensor + noise).clamp_(0.0, 1.0)


def _jpeg_compress_frame(frame_uint8: np.ndarray, quality: int) -> np.ndarray:
    """JPEG round-trip a single HWC uint8 frame in memory."""
    import cv2

    encode_param = [int(cv2.IMWRITE_JPEG_QUALITY), quality]
    _, buf = cv2.imencode(".jpg", frame_uint8, encode_param)
    return cv2.imdecode(buf, cv2.IMREAD_COLOR)


def _apply_jpeg_wash(tensor: torch.Tensor, quality: int) -> torch.Tensor:
    """Apply JPEG compression wash to a [T, C, H, W] float tensor in [0, 1].

    Each frame is encoded and decoded independently (matching real-world
    JPEG artefact patterns).  The same ``quality`` is used for every frame
    and for both real/fake clips in the pair.
    """
    import cv2  # noqa: F811 — imported here for lazy loading

    if quality >= 100:
        return tensor

    device = tensor.device
    T = tensor.shape[0]
    frames_out = []

    for t in range(T):
        # [C,H,W] float [0,1] -> [H,W,C] uint8 BGR (OpenCV convention)
        frame_np = (
            tensor[t].permute(1, 2, 0).mul(255).clamp(0, 255).byte().cpu().numpy()
        )
        # OpenCV expects BGR; torchvision tensors are RGB
        frame_bgr = cv2.cvtColor(frame_np, cv2.COLOR_RGB2BGR)

        compressed = _jpeg_compress_frame(frame_bgr, quality)

        # Back to RGB float [0,1]
        frame_rgb = cv2.cvtColor(compressed, cv2.COLOR_BGR2RGB)
        frame_tensor = (
            torch.from_numpy(frame_rgb).float().div(255.0).permute(2, 0, 1)
        )
        frames_out.append(frame_tensor)

    return torch.stack(frames_out, dim=0).to(device)


def synchronized_frequency_wash(
    real_clip: torch.Tensor,
    fake_clip: torch.Tensor,
    noise_sigma_max: float = 5.0 / 255.0,
    jpeg_quality_min: int = 80,
    jpeg_quality_max: int = 95,
    wash_prob: float = 0.5,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Apply identical random frequency-domain augmentation to both clips.

    A shared random seed ensures the exact same noise realisation and JPEG
    quality is applied to the real and fake clips, so any frequency-domain
    differences between them are eliminated.  This forces the detector to
    rely on temporal kinematics rather than spatial frequency shortcuts.

    Args:
        real_clip: Real video tensor ``[T, C, H, W]`` in ``[0, 1]``.
        fake_clip: Fake video tensor ``[T, C, H, W]`` in ``[0, 1]``.
        noise_sigma_max: Upper bound for Gaussian noise sigma (in [0,1] scale).
        jpeg_quality_min: Minimum JPEG quality for the wash.
        jpeg_quality_max: Maximum JPEG quality for the wash.
        wash_prob: Probability of applying the wash at all (stochastic skip).

    Returns:
        Tuple of (washed_real, washed_fake) with identical augmentation applied.
    """
    # Stochastic skip — some samples see no wash at all
    if random.random() > wash_prob:
        return real_clip, fake_clip

    # Draw shared random parameters
    shared_seed = random.randint(0, 2**31 - 1)
    sigma = random.uniform(0, noise_sigma_max)
    jpeg_quality = random.randint(jpeg_quality_min, jpeg_quality_max)

    # Stage 1: Gaussian noise (synchronized via identical generator seed)
    gen_real = torch.Generator().manual_seed(shared_seed)
    gen_fake = torch.Generator().manual_seed(shared_seed)
    real_clip = _apply_gaussian_noise(real_clip, sigma, gen_real)
    fake_clip = _apply_gaussian_noise(fake_clip, sigma, gen_fake)

    # Stage 2: JPEG compression wash (same quality for both)
    real_clip = _apply_jpeg_wash(real_clip, jpeg_quality)
    fake_clip = _apply_jpeg_wash(fake_clip, jpeg_quality)

    return real_clip, fake_clip


class DualPairSequenceDataset(Dataset):
    """
    Composite dataset that yields both spatial and temporal paired samples.

    Args:
        spatial_dataset: Dataset of spatial (FF++) real/fake pairs.
        temporal_dataset: Dataset of temporal (KiMoI) real/pseudo-fake pairs.
        spatial_ratio: Probability of sampling a spatial pair per __getitem__ call.
            0.5 means equal mix; 0.7 means 70% spatial, 30% temporal.
        freq_wash: Enable synchronized frequency wash on temporal pairs.
            Applies identical random noise + JPEG compression to both real
            and fake clips so the detector cannot exploit frequency-domain
            differences.  Default True.
        freq_wash_noise_sigma_max: Upper bound for Gaussian noise sigma
            (on the [0, 1] intensity scale).  Default 5/255 ≈ 0.0196.
        freq_wash_jpeg_quality_min: Minimum JPEG quality.  Default 80.
        freq_wash_jpeg_quality_max: Maximum JPEG quality.  Default 95.
        freq_wash_prob: Probability of applying the wash per sample.
            Default 0.5 (50% of temporal samples are washed).
    """

    def __init__(
        self,
        spatial_dataset: Dataset,
        temporal_dataset: Dataset,
        spatial_ratio: float = 0.5,
        freq_wash: bool = True,
        freq_wash_noise_sigma_max: float = 5.0 / 255.0,
        freq_wash_jpeg_quality_min: int = 80,
        freq_wash_jpeg_quality_max: int = 95,
        freq_wash_prob: float = 0.5,
        pre_normalized: bool = True,
    ):
        super().__init__()
        self.spatial = spatial_dataset
        self.temporal = temporal_dataset
        self.spatial_ratio = spatial_ratio
        self.freq_wash = freq_wash
        self.freq_wash_noise_sigma_max = freq_wash_noise_sigma_max
        self.freq_wash_jpeg_quality_min = freq_wash_jpeg_quality_min
        self.freq_wash_jpeg_quality_max = freq_wash_jpeg_quality_max
        self.freq_wash_prob = freq_wash_prob
        self.pre_normalized = pre_normalized

        logger.info(
            f"DualPairSequenceDataset: "
            f"spatial={len(self.spatial)}, temporal={len(self.temporal)}, "
            f"ratio={self.spatial_ratio:.2f}, freq_wash={self.freq_wash}, "
            f"pre_normalized={self.pre_normalized}"
        )

    def __len__(self) -> int:
        return len(self.spatial) + len(self.temporal)

    def __getitem__(self, idx: int) -> dict | None:
        # Stochastically choose spatial or temporal based on ratio
        if random.random() < self.spatial_ratio:
            sample = self.spatial[idx % len(self.spatial)]
            pair_type = "spatial"
        else:
            sample = self.temporal[idx % len(self.temporal)]
            pair_type = "temporal"

        if sample is None:
            return None

        # Apply synchronized frequency wash to temporal pairs.
        # The wash expects tensors in [0, 1] range.  When the Albumentations
        # pipeline includes Normalize (pre_normalized=True), tensors arrive in
        # ImageNet-normalized range (~[-2.1, 2.6]).  We must denormalize first,
        # run the wash in [0, 1] space, then renormalize to keep the output
        # distribution consistent with non-washed (spatial) samples.
        if self.freq_wash and pair_type == "temporal":
            real_clip = sample.get("real")
            fake_clip = sample.get("fake")
            if real_clip is not None and fake_clip is not None:
                if self.pre_normalized:
                    real_clip = _denormalize_imagenet(real_clip)
                    fake_clip = _denormalize_imagenet(fake_clip)

                real_clip, fake_clip = synchronized_frequency_wash(
                    real_clip,
                    fake_clip,
                    noise_sigma_max=self.freq_wash_noise_sigma_max,
                    jpeg_quality_min=self.freq_wash_jpeg_quality_min,
                    jpeg_quality_max=self.freq_wash_jpeg_quality_max,
                    wash_prob=self.freq_wash_prob,
                )

                if self.pre_normalized:
                    real_clip = _normalize_imagenet(real_clip)
                    fake_clip = _normalize_imagenet(fake_clip)

                sample["real"] = real_clip
                sample["fake"] = fake_clip

        # Inject pair_type into metadata
        meta = sample.get("meta", {})
        if not isinstance(meta, dict):
            meta = {}
        meta["pair_type"] = pair_type
        sample["meta"] = meta

        return sample
